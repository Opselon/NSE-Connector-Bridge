"""Generate the PyInstaller version file + Windows manifest from
``nse_bridge.BRIDGE_VERSION`` (single source of truth).

Usage:  python scripts/write_version_info.py [--check]
  --check: exit non-zero when the committed files differ (CI freshness
  gate — run after a version bump, before tagging a release).

Outputs:
  version_info.txt                        PyInstaller VSVersionInfo
  windows/NSE-MT5-Bridge.exe.manifest     Windows application manifest
                                          (asInvoker, dpiAware, longPathAware)
  (NOT build/: build/ is gitignored AND PyInstaller --clean wipes it,
  so the manifest lives in the tracked windows/ directory.)

No icon is referenced: the repo has no .ico asset (see docs/RELEASE.md).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from nse_bridge import BRIDGE_VERSION

VERSION_FILE = REPO_ROOT / "version_info.txt"
MANIFEST_FILE = REPO_ROOT / "windows" / "NSE-MT5-Bridge.exe.manifest"


def version_tuple(version: str) -> tuple[int, int, int, int]:
    parts = [int(p) for p in re.split(r"[.-]", version) if p.isdigit()][:4]
    while len(parts) < 4:
        parts.append(0)
    return tuple(parts)  # type: ignore[return-value]


def render_version_info(version: str) -> str:
    major, minor, patch, build = version_tuple(version)
    return f"""# UTF-8
# Generated by scripts/write_version_info.py from nse_bridge.BRIDGE_VERSION
# ({version}). Do not hand-edit — bump BRIDGE_VERSION and re-run the script.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({major}, {minor}, {patch}, {build}),
    prodvers=({major}, {minor}, {patch}, {build}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          u'040904B0',
          [StringStruct(u'CompanyName', u'Opselon'),
           StringStruct(u'FileDescription', u'NSE MT5 Bridge - secure local bridge between MetaTrader 5 and NSE Platform'),
           StringStruct(u'FileVersion', u'{version}'),
           StringStruct(u'InternalName', u'NSE-MT5-Bridge'),
           StringStruct(u'LegalCopyright', u'Copyright (c) Opselon'),
           StringStruct(u'OriginalFilename', u'NSE-MT5-Bridge.exe'),
           StringStruct(u'ProductName', u'NSE MT5 Bridge'),
           StringStruct(u'ProductVersion', u'{version}')])
      ]),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
"""


def render_manifest(version: str) -> str:
    major, minor, patch, build = version_tuple(version)
    return f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<!-- Generated by scripts/write_version_info.py from nse_bridge.BRIDGE_VERSION
     ({version}). The bridge runs unprivileged: asInvoker, no UAC prompt. -->
<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <assemblyIdentity version="{major}.{minor}.{patch}.{build}" processorArchitecture="amd64" name="Opselon.NSE-MT5-Bridge" type="win32" />
  <description>NSE MT5 Bridge - secure local bridge between MetaTrader 5 and NSE Platform</description>
  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">
    <security>
      <requestedPrivileges>
        <requestedExecutionLevel level="asInvoker" uiAccess="false" />
      </requestedPrivileges>
    </security>
  </trustInfo>
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <supportedOS Id="{{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}}" />
      <supportedOS Id="{{1f676c76-80e1-4239-95bb-83d0f6d0da78}}" />
    </application>
  </compatibility>
  <application xmlns="urn:schemas-microsoft-com:asm.v3">
    <windowsSettings>
      <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true</dpiAware>
      <longPathAware xmlns="http://schemas.microsoft.com/SMI/2010/WindowsSettings">true</longPathAware>
    </windowsSettings>
  </application>
</assembly>
"""


def main(argv: list[str] | None = None) -> int:
    check = "--check" in (argv or sys.argv[1:])
    version_info = render_version_info(BRIDGE_VERSION)
    manifest = render_manifest(BRIDGE_VERSION)
    if check:
        ok = True
        for path, content in ((VERSION_FILE, version_info), (MANIFEST_FILE, manifest)):
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                print(f"stale: {path.relative_to(REPO_ROOT)} — re-run scripts/write_version_info.py")
                ok = False
        return 0 if ok else 1
    VERSION_FILE.write_text(version_info, encoding="utf-8")
    MANIFEST_FILE.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_FILE.write_text(manifest, encoding="utf-8")
    print(f"wrote {VERSION_FILE.relative_to(REPO_ROOT)} + {MANIFEST_FILE.relative_to(REPO_ROOT)} ({BRIDGE_VERSION})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
